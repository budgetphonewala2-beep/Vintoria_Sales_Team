#!/usr/bin/env python3
"""Generates every skills/<name>/SKILL.md from the specs in tools/skill_specs.py, with the shared
portable blocks (scripts, web access, prospect folder, pipeline, honesty, compliance). Run after editing
a spec:  python tools/build_skills.py   — then  python tools/validate_skills.py
Check only (CI):  python tools/build_skills.py --check   (exit 1 if any generated file is out of date)

The generated files (every SKILL.md and every references/compliance.md) must not be edited by hand —
edit tools/skill_specs.py or the blocks below instead. Other references/*.md files are hand-written."""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(Path(__file__).resolve().parent))
from skill_specs import SKILLS  # noqa: E402

VERSION = "3.7.0"
AUTHOR = "Zubair Trabzada (original), Radian Marketing (portable upgrade)"
NOTICE = "<!-- Generated by tools/build_skills.py from tools/skill_specs.py. Edit the spec, not this file. -->\n"

BEFORE_HEAD = """## Before you start

1. **Scripts.** `<SCRIPTS>` is the `scripts/` folder of the `sales` skill (`../sales/scripts/` next to this skill's
   folder). Run them with `python` (Windows) or `python3` (macOS/Linux). Each prints one JSON object — treat it as
   evidence to check, not as truth.
"""

PROFILE_REQUIRED = """2. **The seller.** Run `python <SCRIPTS>/seller_profile.py check`. This skill builds its queries, emails or prices
   from `SELLER-PROFILE.json`, so if it isn't `Ready.` run the `sales-setup` interview first (when the user is in a
   hurry, ask just the missing required questions in one message and save the answers with `seller_profile.py set`).
"""

PROFILE_SOFT = """2. **The seller.** Read `SELLER-PROFILE.json` if it exists (`python <SCRIPTS>/seller_profile.py show`). If it doesn't,
   carry on with what the user told you and suggest `sales-setup` at the end — don't block urgent work on it.
"""

BEFORE_TAIL = """3. **The prospect.** Everything about one prospect lives in `prospects/<slug>/` — slug = their domain (`acme.com`), or
   `name@platform` (`anita-desai@linkedin`) for a lead without a website. `python <SCRIPTS>/pipeline.py find <email|name|domain>`
   finds it. Never use one prospect's facts for another.
4. **The pipeline.** `~/.ai-sales-team/pipeline.db` is shared by every agent and session. Before you finish, write
   what you learned (stage, note, next action, attached file) — the next agent only sees what the pipeline shows.
5. **Web access.** Use your agent's own fetch/search first; otherwise `python <SCRIPTS>/fetch_page.py <url> ...` and
   `python <SCRIPTS>/web_search.py "<query>"`; with `APIFY_TOKEN`, `python <SCRIPTS>/lead_sources.py`. If you can't fetch
   something, write "Not found".
6. **Facts only.** Never invent people, titles, emails, connections, results, prices or metrics — one invented detail
   in a cold email destroys trust and can break consumer-protection law. Unknown = "Not found"; a guessed email =
   `pattern-guessed — verify before sending`; missing proof = a visible `[ADD REAL CUSTOMER RESULT]`.
"""


def before(spec):
    return BEFORE_HEAD + (PROFILE_REQUIRED if spec.get("profile") == "required" else PROFILE_SOFT) + BEFORE_TAIL


WRITING = """## Before anything is sent

- **Claim check** every message: `python <SCRIPTS>/claim_check.py --draft <file> --prospect <slug> [--evidence-text "<their post>"]`.
  Rewrite or delete each unsupported sentence and fill every `[PLACEHOLDER]`. Drafts never count as evidence;
  claims about the seller are checked against the real proof in the profile; a hedged consequence ("so phone
  visitors may…") is fine, an unproven number is not.
- **Compliance:** follow `references/compliance.md` — opt-out line, postal address (US), consent rules (UK/EU/CA/AU/NZ).
- **Approval:** show the user the exact final text. Nothing goes out without their OK (a sequence is approved once,
  as a whole).
- **Delivery:** `python <SCRIPTS>/outreach.py doctor` tells you the mode — `autopilot` (queue the approved sequence with
  `outreach.py approve`; it sends each email on its day and stops on any reply), `send-one-by-one` (`outreach.py send`,
  dry run first, then `--send`), or `manual` (the user sends; you `outreach.py log` it so follow-ups get scheduled).
  Never say something was sent unless a script returned `"sent": true` or the user told you so.
- **No booking link** (Calendly, Cal.com, `BOOKING_URL`) until they've replied with interest — a calendar link in a
  cold email reads as presumptuous and lowers replies; `outreach.py` refuses it.
- Never post, comment or DM on social platforms yourself — give the user the text (or a WhatsApp click-to-chat link).
"""

COMPLIANCE = """# Outreach compliance (guidance, not legal advice)

Every sequence must be legal to send:
- Truthful sender identity and subject lines (no fake "Re:"/"Fwd:"), and a working opt-out in every cold
  email (e.g. "Not relevant? Reply 'no' and I won't follow up."). Honour opt-outs immediately.
- **US (CAN-SPAM):** include the sender's physical postal address in the signature.
- **UK (PECR / UK GDPR):** B2B email to corporate addresses is allowed with identification + opt-out; sole
  traders and partnerships need prior consent.
- **EU (GDPR + national ePrivacy laws):** needs a documented legitimate interest and role relevance; Germany
  and some others effectively require prior consent for cold email — flag prospects there.
- **Canada (CASL):** generally requires consent (implied consent only in narrow cases) — flag Canadian prospects.
- **Australia (Spam Act 2003):** needs consent — inferred consent only when the address is conspicuously published
  for business AND your message relates to their role; identify the sender and include a working unsubscribe.
  Flag Australian prospects whose address you found in a database (Apollo etc.) rather than published by them.
- **New Zealand (Unsolicited Electronic Messages Act 2007):** similar consent rule (inferred from conspicuous
  publication); sender details and unsubscribe required.
- **If you are based in India (DPDP Act 2023):** applies to personal data of people in India; for overseas
  prospects the rules above (their country) are the ones that matter.
- Only mention a mutual connection the user confirmed is real and agreed to be named. Never invent one.
- Never post, comment or DM on social platforms on the user's behalf; suggest the message, the user sends it.
- WhatsApp: only to numbers the prospect published for business or shared with you, and only person-to-person
  via a click-to-chat link the user opens — no bulk or automated WhatsApp messages.
- Deliverability: plain text, at most one link, no tracking pixels, no attachments in the first email,
  verified addresses only (never send to `pattern-guessed` or `invalid`), and warm up new sending domains.
- Stop-loss: sending pauses by itself when bounces pass 2 % over the last 14 days (re-verify the list first); a reply
  rate under 1 % after 300 sends means the targeting or offer is wrong — change them, don't send more.
- Over-contact: at most `MAX_TOUCHES_PER_WEEK` (default 4) touches per prospect per week across all channels, and a
  reply on any channel stops every other channel.
- "How did you get my email?" gets an honest answer (their post, their site, a database) and an offer to remove them.
- Volume: start at 5 cold emails a day per inbox (weeks 1-2), then +5 per week, and stay under `DAILY_SEND_LIMIT` (default 30);
  `outreach.py send` refuses suppressed addresses, unverified addresses, missing opt-out lines and over-limit sends.
- Booking links only after interest: a calendar link in a cold email reads as presumptuous and hurts replies;
  `outreach.py` refuses it until the prospect has replied positively.
- Automation: queued sequences only send while an inbox check runs first (`autopilot.py`), so a prospect who
  replied never gets another follow-up. Use a sending domain/inbox you control, warmed up, with SPF/DKIM/DMARC.
- Opt-outs: run `python <SCRIPTS>/reply_triage.py --file reply.txt --apply <slug>` on every reply — it adds
  opt-outs to the do-not-contact list (`pipeline.py suppressed`) so they are never emailed again.
- End the output with a short `Compliance notes` line naming which rules apply to this prospect's country.
"""


def frontmatter(name, description):
    assert len(description) <= 1024, (name, len(description))
    desc = description.replace('"', "'")
    return (f'---\nname: {name}\ndescription: "{desc}"\nlicense: MIT\n'
            'compatibility: "Any agent that supports Agent Skills. Helper scripts need Python 3.9+ (standard library; '
            'reportlab only for PDF). Web access via the agent or the bundled fetch/search scripts."\n'
            f'metadata:\n  author: "{AUTHOR}"\n  version: "{VERSION}"\n---\n' + NOTICE)


def build(spec):
    parts = [frontmatter(spec["name"], spec["description"]), f"# {spec['title']}\n", spec["intro"].strip() + "\n"]
    if spec.get("before", True):
        parts.append(before(spec))
    parts.append(spec["body"].strip() + "\n")
    if spec.get("writes_email"):
        parts.append(WRITING)
    if spec.get("refs"):
        parts.append("## References (read when you reach that step)\n\n" +
                     "\n".join(f"- `references/{f}` — {d}" for f, d in spec["refs"]) + "\n")
    return "\n".join(parts)


def outputs():
    """{path: content} for every generated file."""
    out = {}
    for spec in SKILLS:
        d = ROOT / "skills" / spec["name"]
        out[d / "SKILL.md"] = build(spec)
        if spec.get("writes_email"):
            out[d / "references" / "compliance.md"] = COMPLIANCE
    return out


def main(argv=None):
    check = "--check" in (sys.argv[1:] if argv is None else argv)
    stale = []
    for path, content in outputs().items():
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(str(path.relative_to(ROOT)))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
        if path.name == "SKILL.md":
            print(f"{path.parent.name:<20} {content.count(chr(10)):>4} lines")
    if check:
        print("up to date" if not stale else "out of date (run python tools/build_skills.py):\n  " + "\n  ".join(stale))
        sys.exit(1 if stale else 0)


if __name__ == "__main__":
    main()
